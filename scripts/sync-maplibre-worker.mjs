#!/usr/bin/env node
/**
 * Copy MapLibre's worker chunk into apps/web/public so it can be served from our
 * own origin.
 *
 * Why this is necessary
 * ---------------------
 * MapLibre 6 loads its tile-parsing worker as a *separate module chunk*, and
 * derives the URL from its own `import.meta.url`:
 *
 *     let e = import.meta.url;
 *     if (!/^https?:/.test(e)) return "";        // <-- the problem
 *     return new URL("./maplibre-gl-worker.mjs", e).href;
 *
 * When MapLibre is bundled, `import.meta.url` is no longer an http(s) URL, so
 * that function returns an **empty string** and MapLibre calls `new Worker("")`.
 * An empty worker URL resolves to the page itself, so the browser dutifully
 * starts a worker whose script is the HTML document. It never answers, the style
 * never finishes loading, no vector tile is ever requested — and nothing throws.
 *
 * That was KI-1: a completely blank map with no console error.
 *
 * The fix is to serve the worker ourselves and hand MapLibre an absolute URL via
 * `setWorkerUrl()`. MapLibre 6.7 imported a sibling
 * `maplibre-gl-shared.mjs` chunk; 6.15 ships a self-contained worker instead.
 * We still copy the sibling when the installed package provides it, but runtime
 * correctness is verified by the browser starting the same-origin worker rather
 * than by depending on MapLibre's private chunk layout.
 *
 * The copies are generated rather than committed, so they can never drift from
 * the installed version. Run automatically by the web package's predev/prebuild.
 */
import { copyFile, mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const webDir = path.join(repoRoot, 'apps', 'web');
const outDir = path.join(webDir, 'public', 'maplibre');

/** The worker is required. A sibling shared chunk is copied when MapLibre ships one. */
const REQUIRED = ['maplibre-gl-worker.mjs'];
const OPTIONAL = ['maplibre-gl-shared.mjs'];

const requireFromWeb = createRequire(pathToFileURL(path.join(webDir, 'package.json')).href);

let manifestPath;
try {
  manifestPath = requireFromWeb.resolve('maplibre-gl/package.json');
} catch {
  console.error('✗ maplibre-gl is not installed. Run `pnpm install` first.');
  process.exit(1);
}

const distDir = path.join(path.dirname(manifestPath), 'dist');
const version = JSON.parse(await readFile(manifestPath, 'utf8')).version;

await mkdir(outDir, { recursive: true });

const copied = [];
for (const file of REQUIRED) {
  const source = path.join(distDir, file);
  if (!existsSync(source)) {
    console.error(
      `✗ ${file} is missing from the installed maplibre-gl ${version}.\n` +
        '  The worker layout changed between versions; update this script and\n' +
        '  re-verify that the browser starts the intended worker.',
    );
    process.exit(1);
  }
  const destination = path.join(outDir, file);
  await copyFile(source, destination);
  copied.push(`${file} (${Math.round((await stat(destination)).size / 1024)} KB)`);
}

for (const file of OPTIONAL) {
  const source = path.join(distDir, file);
  if (!existsSync(source)) continue;
  const destination = path.join(outDir, file);
  await copyFile(source, destination);
  copied.push(`${file} (${Math.round((await stat(destination)).size / 1024)} KB)`);
}

// Records which version the served worker came from, so a mismatch after a
// dependency bump is obvious rather than mysterious.
await writeFile(
  path.join(outDir, 'VERSION'),
  `maplibre-gl ${version}\ngenerated by scripts/sync-maplibre-worker.mjs — do not edit\n`,
  'utf8',
);

console.log(`✓ MapLibre ${version} worker synced to public/maplibre: ${copied.join(', ')}`);
